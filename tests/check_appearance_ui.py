"""Verify logo upload and paid design preview against a running local server."""
import os
from io import BytesIO

from PIL import Image
from playwright.sync_api import expect, sync_playwright

base = os.getenv("CSAI_SMOKE_URL", "http://127.0.0.1:3000")
with sync_playwright() as pw:
    browser = pw.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 390, "height": 844})
    page.set_default_timeout(8000)
    page.goto(base + "/auth/demo", wait_until="networkidle")
    if page.get_by_role("heading", name="서비스 정책 확인").count():
        for key in ("terms", "privacy", "ai", "dpa"):
            page.locator("#policy-" + key).check()
        page.get_by_role("button", name="확인하고 계속하기").click()
    page.get_by_role("button", name="메뉴 열기").click()
    page.locator("#demo-view").select_option("free")
    page.locator(".sidebar-tenant").get_by_text("FREE 요금제").wait_for()
    page.goto(base + "/#preview", wait_until="networkidle")
    page.locator(".preview-appearance summary").click()
    live_chat = page.locator(".preview-stage .phone")
    sample = page.locator(".appearance-sample-chat")
    page.locator("#chat-theme").select_option("toss")
    assert "theme-toss" in live_chat.get_attribute("class")
    assert "theme-toss" in sample.get_attribute("class")
    assert page.get_by_role("button", name="디자인 저장").count() == 0
    logo_save = page.get_by_role("button", name="로고 저장")
    expect(logo_save).to_be_disabled()
    page.locator("#logo-file").set_input_files({"name": "large.png", "mimeType": "image/png", "buffer": b"x" * 400001})
    expect(page.locator("#logo-file-status")).to_contain_text("400KB 이하")
    expect(logo_save).to_be_disabled()
    image = BytesIO()
    Image.new("RGB", (120, 120), "#3182f6").save(image, format="PNG")
    choose_file = page.get_by_role("button", name="이미지 선택")
    choose_file.focus()
    with page.expect_file_chooser() as chooser:
        choose_file.press("Enter")
    chooser.value.set_files({"name": "brand.png", "mimeType": "image/png", "buffer": image.getvalue()})
    expect(page.locator(".ui-file-thumbnail img")).to_be_visible()
    expect(sample.locator(".avatar img")).to_be_visible()
    logo_save.click()
    expect(page.locator("#logo-file-status")).to_have_text("로고를 저장했습니다.")
    expect(choose_file).to_be_focused()
    expect(live_chat.locator(".avatar img")).to_be_visible()
    expect(page.locator("#chat-theme")).to_have_value("toss")
    page.get_by_role("button", name="메뉴 열기").click()
    page.locator("#demo-view").select_option("developer")
    page.locator(".sidebar-tenant").get_by_text("개발 검수 · 판매 요금제 아님").wait_for(state="attached")
    page.get_by_role("heading", name="채팅창 미리보기").wait_for()
    page.locator(".preview-appearance summary").click()
    page.get_by_role("button", name="보라 #7639DE").click()
    expect(page.locator("#chat-color")).to_have_value("#7639DE")
    expect(sample.locator(".bubble.user")).to_have_css("background-color", "rgb(118, 57, 222)")
    picker = page.locator("#chat-color-picker")
    picker.evaluate("(el) => { el.value = '#146c50'; el.dispatchEvent(new Event('input')); }")
    expect(page.locator("#chat-color")).to_have_value("#146C50")
    page.locator("#chat-radius").select_option("square")
    expect(sample.locator(".bubble.user")).to_have_css("border-top-left-radius", "5px")
    page.locator("#chat-density").select_option("roomy")
    expect(sample.locator(".messages")).to_have_css("gap", "18px")
    page.get_by_role("button", name="기본값 복원").click()
    expect(page.locator("#chat-color")).to_have_value("#3182F6")
    expect(page.locator("#chat-radius")).to_have_value("rounded")
    page.locator("#chat-color").fill("#oops")
    page.get_by_role("button", name="디자인 저장").click()
    expect(page.locator("#chat-color")).to_be_focused()
    expect(page.locator("#chat-color-error")).to_be_visible()
    page.locator("#chat-color").fill("195FC9")
    page.locator("#chat-theme").select_option("toss")
    page.get_by_role("button", name="디자인 저장").click()
    page.get_by_text("채팅 디자인을 저장했습니다.").wait_for()
    saved = page.evaluate("fetch('/api/appearance').then(r=>r.json())")
    assert saved["theme"] == "toss" and saved["color"].upper() == "#195FC9"
    page.reload(wait_until="networkidle")
    page.wait_for_function("document.querySelector('#chat-theme')?.value === 'toss'")
    assert "theme-toss" in live_chat.get_attribute("class")
    page.get_by_role("button", name="메뉴 열기").click()
    page.locator("#demo-view").select_option("free")
    page.locator(".sidebar-tenant").get_by_text("FREE 요금제").wait_for(state="attached")
    page.locator(".preview-appearance summary").click()
    page.get_by_role("button", name="로고 제거").click()
    expect(page.locator("#logo-file-status")).to_have_text("로고를 제거했습니다.")
    expect(live_chat.locator(".avatar img")).to_have_count(0)
    for width in (320, 390, 768, 1440):
        page.set_viewport_size({"width": width, "height": 844})
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
        assert page.locator(".preview-appearance").evaluate("(el) => el.scrollWidth <= el.clientWidth")
    browser.close()
print("PASS: free logo, design preview, paid design save, mobile width")
