"""Private Supabase/PostgreSQL storage adapter for the application's SQL subset.

The SQLite backend remains the local development default. This adapter never falls
back to SQLite after a PostgreSQL error. A dedicated private schema is required;
browser/anon/authenticated roles never receive access. Transactions serialize
through an advisory lock to preserve the application's existing quota and booking
invariants. No connection is opened by importing this module.
"""
import re
from contextlib import contextmanager
from urllib.parse import urlsplit, parse_qs

SCHEMA='csai_private'
LOCK_ID=437280061932021
ORDERED_TABLES={'message','knowledge_version','event_log','booking_change','delivery','checkout_order','channel_job'}
TOKEN=re.compile(r"""'(?:''|[^'])*'|"(?: "" | [^"] )*"|\?|[A-Za-z_][A-Za-z_0-9]*|.""",re.S|re.X)
IDENT=re.compile(r'[a-z_][a-z_0-9]*\Z')

def checked_name(name):
    if not IDENT.fullmatch(name):raise ValueError('Invalid SQL identifier')
    return '"'+name+'"'

def translate(sql):
    # Preserve literals and quoted identifiers; translate bind markers, not user data.
    ignore=bool(re.match(r'\s*INSERT\s+OR\s+IGNORE\s+INTO\b',sql,re.I))
    if ignore:sql=re.sub(r'^\s*INSERT\s+OR\s+IGNORE\s+INTO\b','INSERT INTO',sql,flags=re.I)
    sql=re.sub(r'\bMAX\s*\(\s*0\s*,','GREATEST(0,',sql)
    ddl=bool(re.match(r'\s*(CREATE\s+TABLE|ALTER\s+TABLE)',sql,re.I))
    result=[]
    for match in TOKEN.finditer(sql):
        token=match.group()
        if token=='?':token='%s'
        elif token=='end':token='"end"'
        elif ddl and token.upper()=='INTEGER':token='BIGINT'
        elif ddl and token.upper()=='REAL':token='DOUBLE PRECISION'
        result.append(token)
    sql=''.join(result)
    if ignore:
        if re.search(r'\bON\s+CONFLICT\b',sql,re.I):raise ValueError('Ambiguous conflict clause')
        sql=sql.rstrip().rstrip(';')+' ON CONFLICT DO NOTHING'
    return sql

class Connection:
    def __init__(self,raw):
        self.raw=raw

    def execute(self,sql,args=()):
        m=re.fullmatch(r'\s*PRAGMA\s+table_info\(([a-z_][a-z_0-9]*)\)\s*',sql,re.I)
        if m:
            with self.raw.cursor(row_factory=None) as cur:
                # SQLite callers only use column position 1 (name).
                cur.execute("SELECT ordinal_position,column_name,data_type,is_nullable,column_default,0 FROM information_schema.columns WHERE table_schema=%s AND table_name=%s ORDER BY ordinal_position",(SCHEMA,m.group(1)))
                return [tuple(r.values()) if isinstance(r,dict) else r for r in cur.fetchall()]
        if "FROM sqlite_master" in sql:
            if sql!="SELECT name FROM sqlite_master WHERE type='table' AND name='subscription'":
                raise ValueError('Unsupported SQLite metadata query')
            return self.raw.execute("SELECT table_name AS name FROM information_schema.tables WHERE table_schema=%s AND table_name='subscription'",(SCHEMA,))
        q=translate(sql)
        cur=self.raw.execute(q,tuple(args)) if args else self.raw.execute(q)
        m=re.match(r'\s*CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+([a-z_][a-z_0-9]*)\s*\(',sql,re.I)
        if m:
            name=m.group(1).lower()
            table=checked_name(name)
            if name in ORDERED_TABLES:
                self.raw.execute('ALTER TABLE '+table+' ADD COLUMN IF NOT EXISTS rowid BIGINT GENERATED BY DEFAULT AS IDENTITY')
                self.raw.execute('CREATE UNIQUE INDEX IF NOT EXISTS '+checked_name(name+'_rowid_unique')+' ON '+table+'(rowid)')
            self.raw.execute('ALTER TABLE '+table+' ENABLE ROW LEVEL SECURITY')
            self.raw.execute('REVOKE ALL ON TABLE '+table+' FROM PUBLIC')
            # Hosted Supabase roles are optional in local PostgreSQL CI.
            for role in ('anon','authenticated'):
                if self.raw.execute('SELECT 1 FROM pg_roles WHERE rolname=%s',(role,)).fetchone():
                    self.raw.execute('REVOKE ALL ON TABLE '+table+' FROM '+checked_name(role))
        return cur

    def executemany(self,sql,parameters):
        with self.raw.cursor() as cur:cur.executemany(translate(sql),parameters)

    def executescript(self,script):
        # All application schema scripts are static DDL; no procedural blocks.
        for statement in script.split(';'):
            if statement.strip():self.execute(statement)

def validate_dsn(dsn):
    if not dsn:raise RuntimeError('DATABASE_URL is required for postgres backend')
    p=urlsplit(dsn)
    if p.scheme not in ('postgresql','postgres') or not p.hostname or not p.username or not p.password:
        raise RuntimeError('Use a complete PostgreSQL connection URL')
    options=parse_qs(p.query)
    if options.get('sslmode',['require'])[-1] not in ('require','verify-ca','verify-full'):
        raise RuntimeError('PostgreSQL SSL is required')
    return dsn

@contextmanager
def connect(dsn,write=False):
    import psycopg
    from psycopg.rows import dict_row
    raw=psycopg.connect(validate_dsn(dsn),sslmode='require' if 'sslmode=' not in dsn else parse_qs(urlsplit(dsn).query)['sslmode'][-1],connect_timeout=10,row_factory=dict_row)
    try:
        raw.execute('SET LOCAL search_path TO csai_private, pg_catalog')
        raw.execute("SET LOCAL statement_timeout TO '45s'")
        raw.execute("SET LOCAL lock_timeout TO '30s'")
        raw.execute('SELECT pg_advisory_xact_lock(%s)',(LOCK_ID,))
        exists=raw.execute("SELECT 1 FROM information_schema.schemata WHERE schema_name='csai_private'").fetchone()
        if not exists:raise RuntimeError('Run the private schema bootstrap SQL first')
        yield Connection(raw)
        if write:raw.commit()
        else:raw.rollback()
    except BaseException:
        raw.rollback();raise
    finally:raw.close()
