import os


def business_info():
    keys = {
        'name': 'CSAI_BUSINESS_NAME',
        'representative': 'CSAI_REPRESENTATIVE',
        'registration': 'CSAI_BUSINESS_NUMBER',
        'address': 'CSAI_BUSINESS_ADDRESS',
        'phone': 'CSAI_CONTACT_PHONE',
        'email': 'CSAI_CONTACT_EMAIL',
        'mail_order': 'CSAI_MAIL_ORDER_NUMBER',
        'privacy_officer': 'CSAI_PRIVACY_OFFICER',
        'privacy_email': 'CSAI_PRIVACY_EMAIL',
    }
    return {key: os.getenv(env, '').strip() for key, env in keys.items()}


def launch_identity_complete():
    info = business_info()
    return all(info[key] for key in ('name', 'representative', 'registration', 'address', 'phone', 'email', 'privacy_officer', 'privacy_email'))


